CREATE TABLE venue
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(200) NOT NULL,
    address       VARCHAR(500) NOT NULL,
    total_rows    INT          NOT NULL CHECK (total_rows BETWEEN 1 AND 26),
    seats_per_row INT          NOT NULL CHECK (seats_per_row >= 1),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE event
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(200)   NOT NULL,
    venue_id   BIGINT         NOT NULL REFERENCES venue (id),
    starts_at  TIMESTAMPTZ    NOT NULL,
    base_price NUMERIC(12, 0) NOT NULL CHECK (base_price > 0),
    vip_rows   INT            NOT NULL DEFAULT 0 CHECK (vip_rows >= 0),
    status     VARCHAR(20)    NOT NULL CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED', 'COMPLETED')),
    version    BIGINT         NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- Seat ids come from a sequence with INCREMENT 50 to match Hibernate allocationSize = 50 (batch inserts).
CREATE SEQUENCE seat_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE seat
(
    id              BIGINT PRIMARY KEY,
    event_id        BIGINT         NOT NULL REFERENCES event (id) ON DELETE CASCADE,
    row_label       VARCHAR(1)     NOT NULL,
    seat_number     INT            NOT NULL CHECK (seat_number >= 1),
    type            VARCHAR(20)    NOT NULL CHECK (type IN ('STANDARD', 'VIP')),
    price           NUMERIC(12, 0) NOT NULL CHECK (price > 0),
    status          VARCHAR(20)    NOT NULL CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD')),
    held_by         VARCHAR(100),
    hold_expires_at TIMESTAMPTZ,
    version         BIGINT         NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),

    -- Business rule enforced by the DB, not only by Java: one seat code per event.
    -- (Also creates an index starting with event_id, used by "seats of event X" queries.)
    CONSTRAINT uq_seat_event_position UNIQUE (event_id, row_label, seat_number),
    -- A HELD seat must know who holds it and until when.
    CONSTRAINT ck_seat_hold CHECK (status <> 'HELD' OR (held_by IS NOT NULL AND hold_expires_at IS NOT NULL))
);
